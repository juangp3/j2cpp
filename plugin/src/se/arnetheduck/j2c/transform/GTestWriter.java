package se.arnetheduck.j2c.transform;

import java.io.IOException;
import java.io.PrintWriter;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.TreeSet;

import org.eclipse.core.runtime.IPath;
import org.eclipse.jdt.core.dom.IMethodBinding;
import org.eclipse.jdt.core.dom.ITypeBinding;

/**
 * Writes a GoogleTest file per JUnit test class. GoogleTest only runs the
 * tests and reports results: the translated test methods keep their Java
 * semantics, a test fails when it throws, as in JUnit, and a failed
 * assumption skips it.
 */
final class GTestWriter {
	static final String HELPER_HPP = "/se/arnetheduck/j2c/resources/j2c_gtest.hpp";

	private GTestWriter() {
	}

	/**
	 * Writes the wrapper and returns its path relative to root. Each test is
	 * added to generated, located with the method declarations in locations
	 * (by method binding key).
	 */
	static String write(IPath root, JUnitSupport.TestClass testClass,
			Map<String, Transformer.MethodLocation> locations,
			List<GeneratedTest> generated) throws IOException {
		ITypeBinding type = testClass.type;
		String file = "test/" + TransformUtil.implName(type, "").replaceAll(
				"\\.cpp$", "_test.cpp");
		String cppType = CName.qualified(type, true);
		String fixture = CName.qualified(type, false).replace("::", "_");

		boolean anyEnabled = false;
		Set<String> includes = new TreeSet<String>();
		includes.add(TransformUtil.include(type));
		for (JUnitSupport.TestMethod test : testClass.tests) {
			IMethodBinding declaration = test.method.getMethodDeclaration();
			Transformer.MethodLocation location = locations.get(declaration
					.getKey());
			generated.add(new GeneratedTest(fixture, test.method.getName(),
					type.getErasure().getQualifiedName(), test.method.getName(),
					declaration.getDeclaringClass().getErasure()
							.getQualifiedName(), location == null ? null
							: location.file, location == null ? 0 : location.line,
					test.disabledReason, file));
			anyEnabled |= test.disabledReason == null;
			if (test.expected != null) {
				includes.add(TransformUtil.include(test.expected));
			}
		}

		PrintWriter out = FileUtil.open(root.append(file).toFile());
		try {
			out.println("// Generated by J2C from " + type.getQualifiedName()
					+ ": runs its JUnit tests with GoogleTest.");
			out.println("#include <j2c_gtest.hpp>");
			out.println();
			for (String include : includes) {
				out.println(include);
			}
			out.println();
			out.println("namespace {");
			out.println();
			out.println("class " + fixture + " : public ::testing::Test {");
			out.println("protected:");
			out.println("    " + cppType + "* test = nullptr;");
			out.println("    static bool suiteFailed;");
			out.println("    static bool suiteAborted;");
			if (anyEnabled && !testClass.beforeAll.isEmpty()) {
				out.println();
				out.println("    static void SetUpTestSuite()");
				out.println("    {");
				lifecycle(out, null, cppType, testClass.beforeAll,
						"ADD_FAILURE() << \"@BeforeAll threw \" << j2c::describe(outcome.thrown);",
						"suiteFailed = true;", "suiteAborted = true;");
				out.println("    }");
			}
			if (anyEnabled && !testClass.afterAll.isEmpty()) {
				out.println();
				out.println("    static void TearDownTestSuite()");
				out.println("    {");
				lifecycle(out, null, cppType, testClass.afterAll,
						"ADD_FAILURE() << \"@AfterAll threw \" << j2c::describe(outcome.thrown);",
						null, null);
				out.println("    }");
			}

			// JUnit creates a new instance for every test
			out.println();
			out.println("    void SetUp() override");
			out.println("    {");
			disabled(out, testClass);
			out.println("        if (suiteAborted) {");
			out.println("            GTEST_SKIP() << \"Assumption failed in @BeforeAll\";");
			out.println("        }");
			out.println("        if (suiteFailed) {");
			out.println("            FAIL() << \"@BeforeAll threw an exception\";");
			out.println("        }");
			out.println("        auto outcome = j2c::run([&] {");
			out.println("            test = new " + cppType + "();");
			for (IMethodBinding method : testClass.beforeEach) {
				out.println("            " + call("test", cppType, method) + ";");
			}
			out.println("        });");
			out.println("        if (outcome.aborted) {");
			out.println("            GTEST_SKIP() << \"Assumption failed in @BeforeEach\";");
			out.println("        }");
			out.println("        if (outcome.thrown != nullptr) {");
			out.println("            FAIL() << \"Constructor or @BeforeEach threw \" << j2c::describe(outcome.thrown);");
			out.println("        }");
			out.println("    }");
			if (!testClass.afterEach.isEmpty()) {
				out.println();
				out.println("    void TearDown() override");
				out.println("    {");
				out.println("        if (test == nullptr) {");
				out.println("            return;");
				out.println("        }");
				lifecycle(out, "test", cppType, testClass.afterEach,
						"ADD_FAILURE() << \"@AfterEach threw \" << j2c::describe(outcome.thrown);",
						null, null);
				out.println("    }");
			}
			out.println("};");
			out.println();
			out.println("bool " + fixture + "::suiteFailed = false;");
			out.println("bool " + fixture + "::suiteAborted = false;");
			out.println();
			out.println("}");

			for (JUnitSupport.TestMethod test : testClass.tests) {
				out.println();
				out.println("TEST_F(" + fixture + ", " + test.method.getName() + ")");
				out.println("{");
				out.println("    auto outcome = j2c::run([&] { "
						+ call("test", cppType, test.method) + "; });");
				out.println("    if (outcome.aborted) {");
				out.println("        GTEST_SKIP() << \"Assumption failed\";");
				out.println("    }");
				if (test.expected == null) {
					out.println("    if (outcome.thrown != nullptr) {");
					out.println("        FAIL() << \"Test threw \" << j2c::describe(outcome.thrown);");
					out.println("    }");
				} else {
					// JUnit 4's messages, with binary class names
					String expected = test.expected.getBinaryName();
					out.println("    if (outcome.thrown == nullptr) {");
					out.println("        FAIL() << \"Expected exception: " + expected
							+ "\";");
					out.println("    }");
					out.println("    if (dynamic_cast< "
							+ CName.qualified(test.expected, true)
							+ "* >(outcome.thrown) == nullptr) {");
					out.println("        FAIL() << \"Unexpected exception, expected<"
							+ expected
							+ "> but was<\" << j2c::className(outcome.thrown) << \">\";");
					out.println("    }");
				}
				out.println("}");
			}
		} finally {
			out.close();
		}
		return file;
	}

	/** Runs lifecycle methods; onFailure and onAbort may be null */
	private static void lifecycle(PrintWriter out, String instance,
			String cppType, Iterable<IMethodBinding> methods, String report,
			String onFailure, String onAbort) {
		out.println("        auto outcome = j2c::run([&] {");
		for (IMethodBinding method : methods) {
			out.println("            " + call(instance, cppType, method) + ";");
		}
		out.println("        });");
		if (onAbort != null) {
			out.println("        if (outcome.aborted) {");
			out.println("            " + onAbort);
			out.println("        }");
		}
		out.println("        if (outcome.thrown != nullptr) {");
		out.println("            " + report);
		if (onFailure != null) {
			out.println("            " + onFailure);
		}
		out.println("        }");
	}

	/** Skips disabled tests before any Java code runs, as JUnit does */
	private static void disabled(PrintWriter out, JUnitSupport.TestClass testClass) {
		StringBuilder entries = new StringBuilder();
		for (JUnitSupport.TestMethod test : testClass.tests) {
			if (test.disabledReason != null) {
				entries.append(entries.length() == 0 ? "" : ", ").append("{ \"")
						.append(test.method.getName()).append("\", ")
						.append(cppString(test.disabledReason)).append(" }");
			}
		}
		if (entries.length() == 0) {
			return;
		}
		out.println("        static const std::map<std::string, std::string> disabled = { "
				+ entries + " };");
		out.println("        auto found = disabled.find(::testing::UnitTest::GetInstance()->current_test_info()->name());");
		out.println("        if (found != disabled.end()) {");
		out.println("            GTEST_SKIP() << \"Disabled in Java\" << (found->second.empty() ? \"\" : \": \" + found->second);");
		out.println("        }");
	}

	private static String call(String instance, String cppType,
			IMethodBinding method) {
		boolean isStatic = TransformUtil.isStatic(method) || instance == null;
		return (isStatic ? cppType + "::" : instance + "->") + CName.of(method)
				+ "()";
	}

	private static String cppString(String value) {
		return "\"" + value.replace("\\", "\\\\").replace("\"", "\\\"")
				.replace("\n", "\\n") + "\"";
	}
}
